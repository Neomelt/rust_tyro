fn main() {
    let x = 5;

    let x = x + 1;

    {
        let x = x * 2;
        println!("The value of x in the inner scope is: {}", x);
    }

    println!("The value of x is: {}", x);
}

// - Rust 的变量遮蔽允许在同一作用域内通过重新声明同名变量，实现变量名复用，并且可以改变变量的类型和值。

// - 这是 Rust 的语法特性，在 C++ 中同一作用域内不允许定义两个同名变量。

// - 遮蔽并不会销毁原变量，而是让后续代码中该名字绑定到新变量，旧变量在其原有作用域内仍然存在，但被“覆盖”了。

// - 当新变量的作用域结束，访问同名变量时会回到之前的那个变量，因为新的绑定不再生效。

// - 这种机制类似于“名字的重新绑定”，但不像函数重载那样有多态行为。

// - Rust 的变量生命周期和作用域遵循普通规则，只是名字绑定层面更灵活。

// - 所以如果要使用原变量的值，需要在遮蔽之前使用它，或者在遮蔽之后重新声明一个新的变量名，如引用。
